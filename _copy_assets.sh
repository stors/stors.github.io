#!/usr/bin/env bash
# Copies the parts of Font Awesome Free and Academicons that the site uses
# from node_modules/ into assets/fontawesome/ and assets/academicons/, and
# generates _includes/head.html from the head.html of the installed
# Minimal Mistakes theme, with the theme's Font Awesome links from jsDelivr
# replaced by links to the local copy. git tracks none of these files.
# Run `npm ci --ignore-scripts` and `bundle install` first. The CI workflow
# runs this script before the Jekyll build, and Dependabot updates the
# versions in package.json and Gemfile.lock.
set -euo pipefail
cd "$(dirname "$0")"

fa_src=node_modules/@fortawesome/fontawesome-free
ai_src=node_modules/academicons
for src in "$fa_src" "$ai_src"; do
    if [ ! -d "$src" ]; then
        echo "ERROR: $src is missing. Run npm ci --ignore-scripts first." >&2
        exit 1
    fi
done

# Font Awesome: the site uses solid, regular, and brands icons.
fa_dest=assets/fontawesome
rm -rf "$fa_dest"
mkdir -p "$fa_dest/css" "$fa_dest/webfonts"
cp "$fa_src/LICENSE.txt" "$fa_dest/"
for style in fontawesome solid regular brands; do
    cp "$fa_src/css/$style.min.css" "$fa_dest/css/"
done
cp "$fa_src/webfonts/fa-solid-900.woff2" "$fa_src/webfonts/fa-regular-400.woff2" \
    "$fa_src/webfonts/fa-brands-400.woff2" "$fa_dest/webfonts/"

# Academicons
ai_dest=assets/academicons
rm -rf "$ai_dest"
mkdir -p "$ai_dest/css" "$ai_dest/fonts"
cp "$ai_src/css/academicons.min.css" "$ai_dest/css/"
cp "$ai_src"/fonts/* "$ai_dest/fonts/"
# The package has no license file; its README states the licenses.
cp "$ai_src/README.md" "$ai_dest/"

# _includes/head.html: the theme loads the latest Font Awesome release from
# jsDelivr with these two lines. Replace them with the local stylesheets.
theme=$(bundle info --path minimal-mistakes-jekyll)
theme_head="$theme/_includes/head.html"
export FA_PRELOAD='<link rel="preload" href="https://cdn.jsdelivr.net/npm/@fortawesome/fontawesome-free@latest/css/all.min.css" as="style" onload="this.onload=null;this.rel='"'stylesheet'"'">'
export FA_NOSCRIPT='<noscript><link rel="stylesheet" href="https://cdn.jsdelivr.net/npm/@fortawesome/fontawesome-free@latest/css/all.min.css"></noscript>'
FA_LINKS=$(for style in fontawesome solid regular brands; do
    printf '<link rel="stylesheet" href="{{ %s | relative_url }}">\n' "'/assets/fontawesome/css/$style.min.css'"
done)
export FA_LINKS
export THEME_NAME=${theme##*/}

head_out=_includes/head.html
tmp=$(mktemp)
if ! awk '
    BEGIN {
        print "{%- comment -%} Generated by _copy_assets.sh from _includes/head.html of " ENVIRON["THEME_NAME"] ". Do not edit. {%- endcomment -%}"
    }
    $0 == ENVIRON["FA_PRELOAD"] { print ENVIRON["FA_LINKS"]; preload++; next }
    $0 == ENVIRON["FA_NOSCRIPT"] { noscript++; next }
    { print }
    END { exit !(preload == 1 && noscript == 1) }
' "$theme_head" > "$tmp"; then
    rm -f "$tmp"
    echo "ERROR: $theme_head does not contain the two Font Awesome lines that" >&2
    echo "_copy_assets.sh replaces (a preload link and a noscript link to" >&2
    echo "fontawesome-free@latest on jsDelivr), each exactly once. The theme" >&2
    echo "has probably changed them. Update FA_PRELOAD and FA_NOSCRIPT in" >&2
    echo "_copy_assets.sh to match the new lines." >&2
    exit 1
fi
chmod 644 "$tmp"
mv "$tmp" "$head_out"
